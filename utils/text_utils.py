def clean_referrer(text):
    """紹介者から括弧内を除去"""
    if pd.isna(text):
        return None
    try:
        text = str(text)
        text = re.sub(r'[\(（].*?[\)）]', '', text)
        return text.strip()
    except Exception as e:
        return str(text) if text is not None else None
